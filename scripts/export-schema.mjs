// Regenerates db/schema.sql (the baseline used to create an empty database) from db/schema.ts.
//   npm run db:export-schema
// Run it after every change to db/schema.ts and commit the result.
import { spawnSync } from "node:child_process";
import fs from "node:fs";

for (const f of [".env.local", ".env"]) {
  try {
    process.loadEnvFile(f);
  } catch {
    /* absent */
  }
}
// drizzle.config.ts insists on a DATABASE_URL even though `export` never connects.
process.env.DATABASE_URL ??= "postgresql://export:export@localhost:5432/export";

const r = spawnSync("npx drizzle-kit export", { encoding: "utf8", shell: true, stdio: ["ignore", "pipe", "pipe"], env: process.env });
if (r.status !== 0 || !/CREATE TABLE/.test(r.stdout)) {
  console.error(r.stderr || r.stdout || "drizzle-kit export failed");
  process.exit(1);
}

const header = `-- Baseline schema for an EMPTY database: every type, table, column, index and foreign key of db/schema.ts.
-- Generated by \`npm run db:export-schema\`. Do not edit by hand; change db/schema.ts and regenerate.
-- Applied by \`npm run db:init\` (scripts/db-init.ts) only when the database has no tables yet.
-- The reporting views are not here: db/views.sql re-creates them on every \`db:init\`.

`;

// Rows the app expects to exist (looked up by name through roleIdOf()). Users and cards are NOT seeded here.
const seed = `
INSERT INTO "roles" ("name") VALUES ('admin'), ('functional'), ('technical') ON CONFLICT ("name") DO NOTHING;
`;

fs.writeFileSync("db/schema.sql", header + r.stdout.trim() + "\n" + seed);
console.log("db/schema.sql written.");
